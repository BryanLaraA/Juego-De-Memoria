    public void actualizarTablero() {

        Carta[][] cartas = juego.getTablero().getTablero();

        for (int i = 0; i < 4; i++) {

            for (int j = 0; j < 8; j++) {

                int indice = i * 8 + j;

                Carta carta = cartas[i][j];

                if (carta.isEstado() || carta.isEmparejada()) {

                    botones[indice].setText(
                            emojis[carta.getNombre() - 1]
                    );

                } else {

                    botones[indice].setText("?");
                }

                botones[indice].setEnabled(
                        !carta.isEmparejada()
                );
            }
        }
    }

